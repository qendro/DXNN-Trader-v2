"""Indicators and signal events shared by the Stage 1 study tools (signal_study, rule_walkforward, drift_forms,
synthetic). Pure functions on the SPEC section 5 bar arrays; no file access.

Conventions (see PREREG_TA_SIGNALS.md section 2 for the wording that is registered):

- An event on decision bar t has a direction d in {-1, +1}: the direction of the move that made it (a break up is +1,
  a touch of a level from below is +1). "Continuation" means a position in direction d entered at the close of bar t;
  "reversal" is the opposite position.
- Indicators on a chart timeframe C use only C bars with end <= end[t] (completed bars).
- Price levels (prior day, prior week, pivots) are the levels known at the START of bar t (D1/W1 bars with
  end <= start[t]). With the level known at end[t], the last decision bar of each trading day would be compared with
  the day it is itself part of, and a touch of "the previous day's high" would be generated by that bar's own high.
"""

import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
import common  # noqa: E402

CHARTS = {"M15": ["M15", "H1", "H4", "D1"], "H1": ["H1", "H4", "D1"], "H4": ["H4", "D1"]}

# Placebos: the same event logic on levels nobody watches. Two placebos per signal, pooled, one on each side of the
# standard setting, so that a smooth dependence of the mechanical reaction on the setting cancels to first order.
SMA_PLACEBO = {50: (37, 67), 200: (163, 237)}
RSI_LEN, RSI_PLACEBO = 14, (11, 17)
BB_LEN, BB_PLACEBO = 20, (15, 26)
DON_LEN, DON_PLACEBO = 20, (15, 26)
LEVEL_PLACEBO_ATR = 0.37            # prior day / week levels and pivots shifted by +-0.37 D1 ATR(14)
GRID_PLACEBO_OFFSETS = (0.37, 0.63)  # a grid of spacing one big figure, offset 0.37 and 0.63 of a figure


def big_figure(pair):
    return 1.0 if pair in common.JPY_PAIRS else 0.01


# SPEC 6b rule 1: every price comparison is made on the price grid (1e-6, USD/JPY 1e-4); equal counts as ABOVE.
# The event code works in grid ticks: mid prices -> rint(price / grid); levels and averages are rounded to ticks.
MID_FIELDS = ("mid_open", "mid_high", "mid_low", "mid_close")
FIGURE_TICKS = 10000            # a big figure is 10,000 ticks for every pair (0.01 / 1e-6, 1.00 / 1e-4)


def grid(pair):
    return 1e-4 if pair in common.JPY_PAIRS else 1e-6


def to_ticks(bars, pair):
    """copy of bars with the mid fields in grid ticks (exact integers held as float64)."""
    g = grid(pair)
    return {tf: {k: (rint(np.asarray(v, np.float64) / g) if k in MID_FIELDS else v) for k, v in b.items()}
            for tf, b in bars.items()}


def rint(x):
    """Round half-up to whole ticks (SPEC 6b rule 1), NaN-safe; matches features.ticks."""
    return np.floor(np.asarray(x, np.float64) + 0.5)


def grid_sma(ticks_arr, n, g):
    """SMA of a series held in grid ticks, rounded to the grid, computed exactly as features.py does (window mean of
    the grid prices, then half-up rounding of mean / grid). An average can fall exactly half-way between two ticks; the result then
    depends on the float error of the mean, so the computation is copied rather than re-derived."""
    from numpy.lib.stride_tricks import sliding_window_view
    p = np.asarray(ticks_arr, np.float64) * g
    out = np.full(len(p), np.nan)
    if len(p) >= n:
        out[n - 1:] = np.mean(sliding_window_view(p, n), axis=1)
    return rint(out / g)


# ------------------------------------------------------------------------------------------------ indicators

def sma(x, n):
    return pd.Series(x).rolling(n, min_periods=n).mean().to_numpy()


def rolling_std(x, n):
    return pd.Series(x).rolling(n, min_periods=n).std(ddof=0).to_numpy()


def wilder(x, n, first=0):
    """Wilder smoothing: seeded with the mean of x[first:first+n], then y = y_prev + (x - y_prev) / n."""
    x = np.asarray(x, float)
    out = np.full(len(x), np.nan)
    if len(x) < first + n:
        return out
    s = np.full(len(x), np.nan)
    s[first + n - 1] = x[first:first + n].mean()
    s[first + n:] = x[first + n:]
    out[first + n - 1:] = pd.Series(s[first + n - 1:]).ewm(alpha=1.0 / n, adjust=False).mean().to_numpy()
    return out


def rsi(close, n=14):
    """Wilder RSI on 0..100 (SPEC 6b rule 2: seeded at bar n with the mean of bars 1..n; 100 when the average loss is
    0, 50 when both averages are 0)."""
    d = np.diff(np.asarray(close, float), prepend=np.nan)
    g = wilder(np.where(d > 0, d, 0.0), n, first=1)
    l = wilder(np.where(d < 0, -d, 0.0), n, first=1)
    with np.errstate(divide="ignore", invalid="ignore"):
        r = 100.0 - 100.0 / (1.0 + g / l)
    r = np.where((l == 0) & np.isfinite(g), 100.0, r)
    r = np.where((l == 0) & (g == 0), 50.0, r)
    return r


def atr(high, low, close, n=14):
    """Wilder ATR (SPEC 6b rule 2: TR undefined on the first bar; seeded at bar n with the mean of TR[1..n])."""
    prev = np.r_[np.nan, close[:-1]]
    tr = np.maximum(high - low, np.maximum(np.abs(high - prev), np.abs(low - prev)))
    return wilder(tr, n, first=1)


def prior_max(x, n):
    """max of x[t-n .. t-1]"""
    return pd.Series(x).rolling(n, min_periods=n).max().shift(1).to_numpy()


def prior_min(x, n):
    return pd.Series(x).rolling(n, min_periods=n).min().shift(1).to_numpy()


def last_completed(c_end, t):
    """index of the last C bar with end <= t (or -1)."""
    return np.searchsorted(c_end, t, side="right") - 1


def take(a, j):
    """a[j] with NaN where j < 0."""
    out = np.full(len(j), np.nan)
    ok = j >= 0
    out[ok] = a[j[ok]]
    return out


# ------------------------------------------------------------------------------------------------ event logic

def side_cross(a, b):
    """+1 where a moves from below b to at-or-above b between t-1 and t (each bar against its own b), -1 for the
    opposite, 0 otherwise or where any input is missing."""
    side = a >= b
    ok = np.isfinite(a) & np.isfinite(b)
    okp = np.r_[False, ok[:-1]]
    sp = np.r_[False, side[:-1]]
    up = ok & okp & side & ~sp
    dn = ok & okp & ~side & sp
    return (up.astype(np.int8) - dn.astype(np.int8))


def level_events(close, high, low, level):
    """Break and touch of a level held fixed at its value for bar t (compared with close[t-1] and close[t]), all in
    grid ticks; a price equal to the level counts as above it (SPEC 6b rules 1 and 6).
    break: +1 close[t-1] < L <= close[t]; -1 close[t-1] >= L > close[t].
    touch: +1 close[t-1] < L, high[t] >= L, close[t] < L (from below); -1 close[t-1] >= L, low[t] < L,
    close[t] >= L (from above). features.py stores only the from-below touch of the prior-day high and the from-above
    touch of the prior-day low, unsigned; the study uses both directions of both."""
    prev = np.r_[np.nan, close[:-1]]
    ok = np.isfinite(level) & np.isfinite(prev)
    with np.errstate(invalid="ignore"):
        up = ok & (prev < level) & (close >= level)
        dn = ok & (prev >= level) & (close < level)
        brk = up.astype(np.int8) - dn.astype(np.int8)
        tu = ok & (prev < level) & (high >= level) & (close < level)
        td = ok & (prev >= level) & (low < level) & (close >= level)
    touch = tu.astype(np.int8) - td.astype(np.int8)
    return brk, touch


def grid_events(close, high, low, spacing, offset):
    """Crosses and touches of the lines offset + k * spacing (grid ticks; a price on a line is above it, so a cell
    holds its lower line). cross: close[t] in another cell than close[t-1], direction of the move. touch: same cell,
    bar t's high reaches the line above (+1) or its low goes below the line below (-1), not both."""
    prev = np.r_[np.nan, close[:-1]]
    ok = np.isfinite(prev) & np.isfinite(close)
    cell = np.floor((close - offset) / spacing)
    pcell = np.floor((prev - offset) / spacing)
    with np.errstate(invalid="ignore"):
        cr = ok & (cell != pcell)
        cross = np.where(cr, np.sign(close - prev), 0).astype(np.int8)
        upper = (cell + 1) * spacing + offset
        lower = cell * spacing + offset
        same = ok & ~cr
        u = same & (high >= upper)
        d = same & (low < lower)
    touch = (u & ~d).astype(np.int8) - (d & ~u).astype(np.int8)
    return cross, touch


def threshold_events(x, lo, hi):
    """Oscillator crossings. enter: crosses above hi (+1) or below lo (-1). exit: crosses back below hi (-1) or back
    above lo (+1)."""
    prev = np.r_[np.nan, x[:-1]]
    ok = np.isfinite(prev) & np.isfinite(x)
    with np.errstate(invalid="ignore"):
        e_up = ok & (prev <= hi) & (x > hi)
        e_dn = ok & (prev >= lo) & (x < lo)
        x_dn = ok & (prev > hi) & (x <= hi)
        x_up = ok & (prev < lo) & (x >= lo)
    enter = e_up.astype(np.int8) - e_dn.astype(np.int8)
    exit_ = x_up.astype(np.int8) - x_dn.astype(np.int8)
    return enter, exit_


def bb_events(close, n, k=2.0):
    """+1 where the close moves to or above the upper band (SMA n + k population sd, rounded to the grid), -1 where
    it moves below the lower band."""
    m, s = sma(close, n), rolling_std(close, n)
    with np.errstate(invalid="ignore"):
        above = close >= rint(m + k * s)
        below = close < rint(m - k * s)
    ok = np.isfinite(m) & np.isfinite(s)
    okp = np.r_[False, ok[:-1]]
    ap, bp = np.r_[False, above[:-1]], np.r_[False, below[:-1]]
    return ((ok & okp & above & ~ap).astype(np.int8) - (ok & okp & below & ~bp).astype(np.int8))


def donchian_events(close, high, low, n):
    """SPEC ev_donchian20_break: close at or above the prior n-bar high (+1) or below the prior n-bar low (-1)."""
    hi, lo = prior_max(high, n), prior_min(low, n)
    with np.errstate(invalid="ignore"):
        return ((close >= hi).astype(np.int8) - (close < lo).astype(np.int8))


def to_decision(c_bars, x_bars, c_events):
    """Flag a C-bar event on the first X bar at whose end the C bar is complete (SPEC section 6): the latest non-zero
    event among the C bars that became known at that row (as features.newly_known)."""
    j = last_completed(c_bars["end"], x_bars["end"])
    jp = np.r_[-1, j[:-1]]
    last_ev = np.maximum.accumulate(np.where(c_events != 0, np.arange(len(c_events)), -1))
    k = np.where(j >= 0, last_ev[np.maximum(j, 0)], -1)
    new = (j >= 0) & (k > jp)
    out = np.zeros(len(j), np.int8)
    out[new] = c_events[k[new]]
    return out


def combine(series_list):
    """first non-zero event across several event series (used for the five pivot levels)."""
    out = np.zeros(len(series_list[0]), np.int8)
    for s in series_list:
        out = np.where(out == 0, s, out).astype(np.int8)
    return out


# ------------------------------------------------------------------------------------------------ levels

STUB_MINUTES = 360   # as features.py: D1 bars with fewer minutes are holiday stubs, left out of D1 levels and charts


def d1_full(bars):
    d1 = bars["D1"]
    keep = d1["n_minutes"] >= STUB_MINUTES
    return {k: np.asarray(v)[keep] for k, v in d1.items()}


def chart(bars, C):
    return d1_full(bars) if C == "D1" else bars[C]


def day_levels(bars, x):
    """Levels known at the start of each X bar: prior (non-stub) day H/L/C, pivots, prior week H/L, D1 ATR(14)."""
    d1, w1 = d1_full(bars), bars["W1"]
    jd = last_completed(d1["end"], x["start"])
    jw = last_completed(w1["end"], x["start"])
    H, L, C = take(d1["mid_high"], jd), take(d1["mid_low"], jd), take(d1["mid_close"], jd)
    P = (H + L + C) / 3.0
    lv = {"pdh": H, "pdl": L, "pdc": C,
          "pivot_p": rint(P), "pivot_r1": rint(2 * P - L), "pivot_s1": rint(2 * P - H), "pivot_r2": rint(P + (H - L)),
          "pivot_s2": rint(P - (H - L)),
          "pwh": take(w1["mid_high"], jw), "pwl": take(w1["mid_low"], jw), "pwc": take(w1["mid_close"], jw),
          "atr_d1": take(atr(d1["mid_high"], d1["mid_low"], d1["mid_close"]), jd)}
    return lv


PIVOTS = ["pivot_p", "pivot_r1", "pivot_s1", "pivot_r2", "pivot_s2"]


# ------------------------------------------------------------------------------------------------ the catalogue

def signal_catalogue(bars, X, pair):
    """All signals for one pair and decision timeframe X. Returns a list of dicts
    {name, family, chart, std: int8 array, placebo: [int8 arrays]} aligned with bars[X]. Takes bars in prices."""
    bars = to_ticks(bars, pair)
    x = bars[X]
    c, h, l = x["mid_close"], x["mid_high"], x["mid_low"]
    out = []

    def add(name, family, chart, std, placebo):
        out.append({"name": name, "family": family, "chart": chart, "std": std, "placebo": placebo})

    # moving averages on every chart timeframe
    for C in CHARTS[X]:
        cb = chart(bars, C)
        cc = cb["mid_close"]
        smas = {n: grid_sma(cc, n, grid(pair)) for n in (50, 200) + SMA_PLACEBO[50] + SMA_PLACEBO[200]}
        for n in (50, 200):
            std = to_decision(cb, x, side_cross(cc, smas[n]))
            plc = [to_decision(cb, x, side_cross(cc, smas[m])) for m in SMA_PLACEBO[n]]
            add(f"px_sma{n}_cross@{C}", "ma", C, std, plc)
        std = to_decision(cb, x, side_cross(smas[50], smas[200]))
        plc = [to_decision(cb, x, side_cross(smas[a], smas[b])) for a, b in zip(SMA_PLACEBO[50], SMA_PLACEBO[200])]
        add(f"sma50_200_cross@{C}", "ma", C, std, plc)

    # oscillators and channels on the decision timeframe
    ent, ext = threshold_events(rsi(c, RSI_LEN), 30.0, 70.0)
    pl = [threshold_events(rsi(c, m), 30.0, 70.0) for m in RSI_PLACEBO]
    add("rsi_enter_30_70", "rsi", X, ent, [p[0] for p in pl])
    add("rsi_exit_30_70", "rsi", X, ext, [p[1] for p in pl])
    add("bb20_outside", "bollinger", X, bb_events(c, BB_LEN), [bb_events(c, m) for m in BB_PLACEBO])
    add("donchian20_break", "donchian", X, donchian_events(c, h, l, DON_LEN),
        [donchian_events(c, h, l, m) for m in DON_PLACEBO])

    # price levels
    lv = day_levels(bars, x)
    k = LEVEL_PLACEBO_ATR * lv["atr_d1"]
    for name, fam in (("pdh", "prior_day"), ("pdl", "prior_day"), ("pwh", "prior_week"), ("pwl", "prior_week")):
        b0, t0 = level_events(c, h, l, lv[name])
        bp, tp = level_events(c, h, l, rint(lv[name] + k))
        bm, tm = level_events(c, h, l, rint(lv[name] - k))
        add(f"{name}_break", fam, "D1" if fam == "prior_day" else "W1", b0, [bp, bm])
        add(f"{name}_touch", fam, "D1" if fam == "prior_day" else "W1", t0, [tp, tm])
    piv = {s: [level_events(c, h, l, rint(lv[p] + s * k)) for p in PIVOTS] for s in (0, 1, -1)}
    pc = {s: combine([e[0] for e in piv[s]]) for s in piv}
    pt = {s: np.where(pc[s] == 0, combine([e[1] for e in piv[s]]), 0).astype(np.int8) for s in piv}
    add("pivot_cross", "pivot", "D1", pc[0], [pc[1], pc[-1]])
    add("pivot_touch", "pivot", "D1", pt[0], [pt[1], pt[-1]])

    # round numbers
    fig = FIGURE_TICKS
    big = grid_events(c, h, l, fig, 0.0)
    half = grid_events(c, h, l, fig, fig // 2)
    plc = [grid_events(c, h, l, fig, round(o * fig)) for o in GRID_PLACEBO_OFFSETS]
    add("round_big_cross", "round", X, big[0], [p[0] for p in plc])
    add("round_big_touch", "round", X, big[1], [p[1] for p in plc])
    add("round_half_cross", "round", X, half[0], [p[0] for p in plc])
    add("round_half_touch", "round", X, half[1], [p[1] for p in plc])
    return out


def spec_event_columns(bars, X, pair):
    """The event columns that SPEC section 6 names, computed with this module's definitions. Used to cross-check a
    feature table built by features.py, and by synthetic.make_features. Takes bars in prices."""
    bars = to_ticks(bars, pair)
    x = bars[X]
    c, h, l = x["mid_close"], x["mid_high"], x["mid_low"]
    lv = day_levels(bars, x)
    out = {}
    out["ev_pdh_break"], t = level_events(c, h, l, lv["pdh"])
    out["ev_pdh_touch"] = (t == 1).astype(np.int8)            # features.py: from below only, unsigned
    out["ev_pdl_break"], t = level_events(c, h, l, lv["pdl"])
    out["ev_pdl_touch"] = (t == -1).astype(np.int8)           # features.py: from above only, unsigned
    out["ev_donchian20_break"] = donchian_events(c, h, l, DON_LEN)
    out["ev_round_big_cross"] = grid_events(c, h, l, FIGURE_TICKS, 0.0)[0]
    for C in CHARTS[X]:
        cb = chart(bars, C)
        for n in (50, 200):
            out[f"{C}_ev_sma{n}_cross"] = to_decision(cb, x, side_cross(cb["mid_close"], grid_sma(cb["mid_close"], n, grid(pair))))
    return out
